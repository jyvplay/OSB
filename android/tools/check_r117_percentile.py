#!/usr/bin/env python3
"""R117 gate: the percentile variants and the `A` aggregate family, their oracle corpus, and their tests must agree.

The product change is small — four percentile names added to an existing dispatch branch, one new helper for the
`A` family, four OOXML export prefixes — and the ways such a change can pass review while being useless are equally
small: a name added to the helper but not to the dispatch, the exclusive rank implemented as the inclusive one (the
two differ only in the rank formula, so a copy-paste passes every legacy test), the `A` family implemented by reusing
`collectNumericAggregate` (which *ignores* text in ranges — exactly the behaviour the `A` family exists to differ
from), a corpus generated by the code under test instead of by the documented definitions, or a fixture edited by
hand so the recorded evidence no longer means anything.

Rules:

  R117-1 registered         each of the thirteen names is dispatched and implemented exactly once, and the four
                            dotted names are exported with the `_xlfn.` prefix.
  R117-2 covered            every registered name has corpus rows; the exclusive variants have refusal rows; the
                            `A` family has text, logical and empty-cell rows.
  R117-3 well-formed        no duplicated row, no unknown function, no error literal outside the seven, every data
                            token parses.
  R117-4 coherent           the corpus satisfies the identities of its own functions, recomputed from the corpus.
  R117-5 reproducible       the committed corpus is byte-identical to what the generator renders.
  R117-6 tested             the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases.
  R117-7 no regression      the legacy inclusive percentile kernel, MODE.SNGL and the STDEV/VAR kernels are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI; this gate decides whether that test
would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r117_percentile_corpus import render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/PercentileFunctionTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r117/percentile_corpus.tsv'
PERCENTILE_NAMES = ('PERCENTILE', 'PERCENTILE.INC', 'PERCENTILE.EXC', 'QUARTILE', 'QUARTILE.INC', 'QUARTILE.EXC')
A_NAMES = ('AVERAGEA', 'MAXA', 'MINA', 'VARA', 'VARPA', 'STDEVA', 'STDEVPA')
NAMES = PERCENTILE_NAMES + A_NAMES
DOTTED = ('PERCENTILE.INC', 'PERCENTILE.EXC', 'QUARTILE.INC', 'QUARTILE.EXC')
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
HELPERS = ('cell', 'number', 'shown')
MAX_HELPER_ARGS = 3
LEGACY_RANK = 'val pos = if (exclusive) k * (sorted.size + 1) - 1.0 else k * (sorted.size - 1)'
MODE_KERNEL = '"MODE.SNGL" -> {'
STDEV_KERNEL = '"STDEV.S", "STDEV.P", "VAR.S", "VAR.P" -> {'

RULES = {
    'R117-1': 'each of the thirteen names is dispatched and implemented exactly once, and the dotted names are exported',
    'R117-2': 'every registered name has corpus rows, with refusal and mixed-type rows where the semantics need them',
    'R117-3': 'no duplicated corpus row, no unknown function, no error literal outside the seven',
    'R117-4': 'the corpus satisfies the mathematical identities of the functions it pins',
    'R117-5': 'the committed corpus is byte-identical to what the generator renders',
    'R117-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R117-7': 'the legacy percentile kernel and the MODE/STDEV/VAR kernels are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R117-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R117-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 4:
            raise SystemExit(f'R117-3: corpus line {index} is not four columns')
        out.append((parts[0], parts[1], parts[2], parts[3]))
    return out


def token_value(token: str) -> float | None:
    """The `A`-family value of one data token, or None for an empty cell."""
    if token == 'EMPTY':
        return None
    if token == 'TRUE':
        return 1.0
    if token == 'FALSE':
        return 0.0
    if token.startswith('"'):
        return 0.0
    return float(token)


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    if source.count('evalPercentileOrQuartile(name, args, env)') != 1:
        found.append('R117-1: the percentile dispatch call is not present exactly once')
    if source.count('evalAggregateA(name, args, env)') != 1:
        found.append('R117-1: the A-family dispatch call is not present exactly once')
    if source.count('private fun evalAggregateA') != 1:
        found.append('R117-1: evalAggregateA is not defined exactly once')
    if source.count('private fun evalPercentileOrQuartile') != 1:
        found.append('R117-1: evalPercentileOrQuartile is not defined exactly once')
    for name in NAMES:
        if f'"{name}"' not in source:
            found.append(f'R117-1: {name} does not appear in the product source')
    for name in DOTTED:
        if f'"{name}"' not in spill:
            found.append(f'R117-1: {name} is missing from the OOXML export prefix list')
    return found


def helper_arities(text: str, helper: str) -> list[int]:
    """Top-level argument counts of every `helper(...)` call, so a test cannot pass a Kotlin arity error to CI."""
    counts: list[int] = []
    for match in re.finditer(r'\b%s\(' % helper, text):
        depth, commas, index = 0, 0, match.end() - 1
        while index < len(text):
            character = text[index]
            if character == '"':
                index += 1
                while index < len(text) and text[index] != '"':
                    index += 2 if text[index] == '\\' else 1
            elif character == '(':
                depth += 1
            elif character == ')':
                depth -= 1
                if depth == 0:
                    counts.append(commas + 1 if text[match.end():index].strip() or commas else 0)
                    break
            elif character == ',' and depth == 1:
                commas += 1
            index += 1
    return counts


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    # R117-2 coverage.
    counts: dict[str, int] = {}
    for function, _data, _k, _expected in corpus:
        counts[function] = counts.get(function, 0) + 1
    for name in NAMES:
        if counts.get(name, 0) < 20:
            found.append(f'R117-2: {name} has only {counts.get(name, 0)} rows; at least 20 are required')
    for name in ('PERCENTILE.EXC', 'QUARTILE.EXC'):
        refusals = sum(1 for f, _d, _k, e in corpus if f == name and e == '#NUM!')
        if refusals < 5:
            found.append(f'R117-2: {name} has only {refusals} refusal rows; at least 5 are required')
    a_data = {data for f, data, _k, _e in corpus if f in A_NAMES}
    if not any('"' in data for data in a_data):
        found.append('R117-2: no A-family row carries a text cell')
    if not any('TRUE' in data or 'FALSE' in data for data in a_data):
        found.append('R117-2: no A-family row carries a logical cell')
    if not any('EMPTY' in data for data in a_data):
        found.append('R117-2: no A-family row carries an empty cell')
    if not any('#N/A' in data for data in a_data):
        found.append('R117-2: no A-family row carries an error cell')

    # R117-3 shape.
    seen: set[tuple[str, str, str]] = set()
    for function, data, k, expected in corpus:
        key = (function, data, k)
        if key in seen:
            found.append(f'R117-3: duplicate corpus row {function}({data}, {k})')
        seen.add(key)
        if function not in NAMES:
            found.append(f'R117-3: corpus names an unregistered function {function}')
        if function in PERCENTILE_NAMES and not k:
            found.append(f'R117-3: {function} row has no rank')
        if function in A_NAMES and k:
            found.append(f'R117-3: {function} row carries a rank it does not take')
        for token in data.split(','):
            if token == '#N/A':
                continue
            try:
                token_value(token)
            except ValueError:
                found.append(f'R117-3: {function} data token {token!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R117-3: {function}({data}, {k}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R117-3: {function}({data}, {k}) expects a non-finite number')

    # R117-4 coherence, recomputed from the corpus itself.
    def numeric(function: str) -> dict[tuple[str, str], float]:
        return {(data, k): float(e) for f, data, k, e in corpus if f == function and not e.startswith('#')}

    legacy, inc = numeric('PERCENTILE'), numeric('PERCENTILE.INC')
    for key in sorted(set(legacy) & set(inc)):
        if abs(legacy[key] - inc[key]) > 1e-12 * max(1.0, abs(legacy[key])):
            found.append(f'R117-4: PERCENTILE and PERCENTILE.INC disagree at {key}')
    quartile_inc, percentile_inc = numeric('QUARTILE.INC'), numeric('PERCENTILE.INC')
    for (data, q), value in sorted(quartile_inc.items()):
        counterpart = percentile_inc.get((data, repr(float(q) * 0.25)))
        if counterpart is not None and abs(value - counterpart) > 1e-12 * max(1.0, abs(value)):
            found.append(f'R117-4: QUARTILE.INC({data}, {q}) is not PERCENTILE.INC at {float(q) * 0.25}')
    by_data: dict[str, list[tuple[float, float]]] = {}
    for (data, k), value in inc.items():
        by_data.setdefault(data, []).append((float(k), value))
    for data, pairs in by_data.items():
        ordered = sorted(pairs)
        for (k1, v1), (k2, v2) in zip(ordered, ordered[1:]):
            if v2 < v1 - 1e-12:
                found.append(f'R117-4: PERCENTILE.INC is not non-decreasing in k for {data} ({k1}->{v1}, {k2}->{v2})')
    for function, data, _k, expected in corpus:
        if function != 'AVERAGEA' or expected.startswith('#'):
            continue
        values = [v for v in (token_value(t) for t in data.split(',')) if v is not None]
        if values and abs(sum(values) / len(values) - float(expected)) > 1e-12 * max(1.0, abs(float(expected))):
            found.append(f'R117-4: AVERAGEA({data}) is not the mean with text as 0')
    maxa, mina = numeric('MAXA'), numeric('MINA')
    for key in sorted(set(maxa) & set(mina)):
        if maxa[key] < mina[key] - 1e-12:
            found.append(f'R117-4: MAXA < MINA at {key}')

    # R117-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R117-5: the committed corpus differs from what tools/gen_r117_percentile_corpus.py renders')

    # R117-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R117-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R117-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 14:
        found.append(f'R117-6: the Kotlin test has {test.count("@Test")} cases; at least 14 are required')
    for helper in HELPERS:
        for arity in helper_arities(test, helper):
            if arity > MAX_HELPER_ARGS:
                found.append(f'R117-6: {helper}(...) is called with {arity} arguments; the helpers take a formula and '
                             f'at most two values')
    if '/r117/percentile_corpus.tsv' not in test:
        found.append('R117-6: the Kotlin test does not read the R117 corpus resource')
    for literal in ('#NUM!', '#DIV/0!', '#VALUE!', '#NAME?', '#N/A'):
        if literal not in test:
            found.append(f'R117-6: the Kotlin test never asserts {literal}')

    # R117-7 no regression in the kernels this round reuses.
    for needle in (LEGACY_RANK, MODE_KERNEL, STDEV_KERNEL):
        if needle not in source:
            found.append(f'R117-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[3].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R117_PERCENTILE_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
