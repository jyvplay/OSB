#!/usr/bin/env python3
"""R119 gate: the legacy statistical aliases and FORECAST, their oracle corpus, and their tests must agree.

The product change is small — five alias dispatch branches that delegate to the modern kernels they rename,
one new helper for `FORECAST`/`FORECAST.LINEAR`, one OOXML export prefix — and the ways such a change can pass
review while being useless are equally small: a name added to the dispatch but not to the corpus, an alias
delegating to the wrong kernel (sample for population, or vice versa — the two differ only in the divisor, so
a copy-paste passes every legacy test), `FORECAST` implemented as `SLOPE` alone (forgetting the intercept),
a corpus generated by the code under test instead of by the documented definitions, or a fixture edited by
hand so the recorded evidence no longer means anything.

Rules:

  R119-1 registered         each of the seven names is dispatched exactly once, `evalForecast` is defined
                            exactly once, and `FORECAST.LINEAR` is exported with the `_xlfn.` prefix.
  R119-2 covered            every registered name has at least twenty corpus rows; MODE has refusal rows;
                            FORECAST has refusal rows; the single-array family has text, logical and empty rows.
  R119-3 well-formed        no duplicated row, no unknown function, no error literal outside the seven, every
                            data token parses.
  R119-4 coherent           the corpus satisfies the identities of its own functions, recomputed from the corpus.
  R119-5 reproducible       the committed corpus is byte-identical to what the generator renders.
  R119-6 tested             the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases.
  R119-7 no regression      the percentile, MODE/STDEV/VAR and A-family kernels this round reuses are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI; this gate decides whether that test
would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r119_legacy_stats_corpus import render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/LegacyStatsFunctionTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r119/legacy_stats_corpus.tsv'
SINGLE_NAMES = ('VAR', 'VARP', 'STDEVP', 'MODE')
PAIR_NAMES = ('COVARIANCE',)
FORECAST_NAMES = ('FORECAST', 'FORECAST.LINEAR')
NAMES = SINGLE_NAMES + PAIR_NAMES + FORECAST_NAMES
DISPATCH = {
    '"VAR" -> evalEssential("VAR.S", args, env)': 'VAR',
    '"VARP" -> evalEssential("VAR.P", args, env)': 'VARP',
    '"STDEVP" -> evalEssential("STDEV.P", args, env)': 'STDEVP',
    '"MODE" -> evalEssential("MODE.SNGL", args, env)': 'MODE',
    '"COVARIANCE" -> evalR51ScalarFunction("COVARIANCE.P", args, env)': 'COVARIANCE',
    '"FORECAST", "FORECAST.LINEAR" -> evalForecast(args, env)': 'FORECAST',
}
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
HELPERS = ('cell', 'number', 'shown')
MAX_HELPER_ARGS = 3
LEGACY_RANK = 'val pos = if (exclusive) k * (sorted.size + 1) - 1.0 else k * (sorted.size - 1)'
MODE_KERNEL = '"MODE.SNGL" -> {'
STDEV_KERNEL = '"STDEV.S", "STDEV.P", "VAR.S", "VAR.P" -> {'
A_DISPATCH = '"AVERAGEA", "MAXA", "MINA", "VARA", "VARPA", "STDEVA", "STDEVPA" -> evalAggregateA(name, args, env)'

RULES = {
    'R119-1': 'each of the seven names is dispatched exactly once, evalForecast is defined once, FORECAST.LINEAR is exported',
    'R119-2': 'every registered name has at least twenty corpus rows, with refusal and mixed-type rows where the semantics need them',
    'R119-3': 'no duplicated corpus row, no unknown function, no error literal outside the seven',
    'R119-4': 'the corpus satisfies the mathematical identities of the functions it pins',
    'R119-5': 'the committed corpus is byte-identical to what the generator renders',
    'R119-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R119-7': 'the percentile, MODE/STDEV/VAR and A-family kernels this round reuses are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R119-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R119-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 5:
            raise SystemExit(f'R119-3: corpus line {index} is not five columns')
        out.append((parts[0], parts[1], parts[2], parts[3], parts[4]))
    return out


def token_parses(token: str) -> bool:
    if token in ('EMPTY', 'TRUE', 'FALSE', '#N/A'):
        return True
    if token.startswith('"') and token.endswith('"') and len(token) >= 2:
        return True
    try:
        float(token)
        return True
    except ValueError:
        return False


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    for dispatch, name in DISPATCH.items():
        if source.count(dispatch) != 1:
            found.append(f'R119-1: the dispatch for {name} is not present exactly once: {dispatch}')
    if len(re.findall(r'\bprivate\s+fun\s+evalForecast\s*\(', source)) != 1:
        found.append('R119-1: evalForecast is not defined exactly once')
    if source.count('evalForecast(args, env)') != 1:
        found.append('R119-1: the evalForecast dispatch call is not present exactly once')
    for name in NAMES:
        if f'"{name}"' not in source:
            found.append(f'R119-1: {name} does not appear in the product source')
    if '"FORECAST.LINEAR"' not in spill:
        found.append('R119-1: FORECAST.LINEAR is missing from the OOXML export prefix list')
    for legacy in ('FORECAST', 'VAR', 'VARP', 'STDEVP', 'MODE', 'COVARIANCE'):
        if f'"{legacy}"' in spill:
            found.append(f'R119-1: legacy name {legacy} must be stored bare, not with the _xlfn. prefix')
    return found


def helper_arities(text: str, helper: str) -> list[int]:
    """Top-level argument counts of every `helper(...)` call, so a test cannot pass a Kotlin arity error to CI."""
    counts: list[int] = []
    for match in re.finditer(r'\b%s\(' % helper, text):
        depth, commas, index = 0, 0, match.end() - 1
        while index < len(text):
            character = text[index]
            if character == '"':
                index += 1
                while index < len(text) and text[index] != '"':
                    index += 2 if text[index] == '\\' else 1
            elif character == '(':
                depth += 1
            elif character == ')':
                depth -= 1
                if depth == 0:
                    counts.append(commas + 1 if text[match.end():index].strip() or commas else 0)
                    break
            elif character == ',' and depth == 1:
                commas += 1
            index += 1
    return counts


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    # R119-2 coverage.
    counts: dict[str, int] = {}
    for function, _a, _b, _c, _expected in corpus:
        counts[function] = counts.get(function, 0) + 1
    for name in NAMES:
        if counts.get(name, 0) < 20:
            found.append(f'R119-2: {name} has only {counts.get(name, 0)} rows; at least 20 are required')
    mode_refusals = sum(1 for f, _a, _b, _c, e in corpus if f == 'MODE' and e == '#N/A')
    if mode_refusals < 5:
        found.append(f'R119-2: MODE has only {mode_refusals} refusal rows; at least 5 are required')
    forecast_refusals = sum(1 for f, _a, _b, _c, e in corpus if f in FORECAST_NAMES and e == '#DIV/0!')
    if forecast_refusals < 5:
        found.append(f'R119-2: FORECAST has only {forecast_refusals} refusal rows; at least 5 are required')
    single_data = {a for f, a, _b, _c, _e in corpus if f in SINGLE_NAMES}
    if not any('"' in data for data in single_data):
        found.append('R119-2: no single-array row carries a text cell')
    if not any('TRUE' in data or 'FALSE' in data for data in single_data):
        found.append('R119-2: no single-array row carries a logical cell')
    if not any('EMPTY' in data for data in single_data):
        found.append('R119-2: no single-array row carries an empty cell')
    if not any('#N/A' in data for data in single_data):
        found.append('R119-2: no single-array row carries an error cell')

    # R119-3 shape.
    seen: set[tuple[str, str, str, str]] = set()
    for function, a, b, c, expected in corpus:
        key = (function, a, b, c)
        if key in seen:
            found.append(f'R119-3: duplicate corpus row {function}({a}, {b}, {c})')
        seen.add(key)
        if function not in NAMES:
            found.append(f'R119-3: corpus names an unregistered function {function}')
        if function in SINGLE_NAMES and (b or c):
            found.append(f'R119-3: {function} row carries arguments it does not take')
        if function == 'COVARIANCE' and (not b or c):
            found.append(f'R119-3: COVARIANCE row is missing its second array or carries a scalar')
        if function in FORECAST_NAMES and (not b or not c):
            found.append(f'R119-3: {function} row is missing an array or its prediction point')
        for column in (a, b):
            if not column:
                continue
            for token in column.split(','):
                if not token_parses(token):
                    found.append(f'R119-3: {function} data token {token!r} does not parse')
        if c and not token_parses(c):
            found.append(f'R119-3: {function} prediction point {c!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R119-3: {function}({a}, {b}, {c}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R119-3: {function}({a}, {b}, {c}) expects a non-finite number')

    # R119-4 coherence, recomputed from the corpus itself.
    def numeric(function: str) -> dict[tuple[str, str, str], float]:
        return {(a, b, c): float(e) for f, a, b, c, e in corpus if f == function and not e.startswith('#')}

    var, varp, stdevp = numeric('VAR'), numeric('VARP'), numeric('STDEVP')
    for key in sorted(set(var) & set(varp)):
        a, _b, _c = key
        n = len([t for t in a.split(',') if t not in ('EMPTY', 'TRUE', 'FALSE') and not t.startswith('"')])
        if n >= 2 and abs(var[key] - varp[key] * n / (n - 1)) > 1e-12 * max(1.0, abs(var[key])):
            found.append(f'R119-4: VAR and VARP disagree on the sample/population split at {key}')
    for key in sorted(set(varp) & set(stdevp)):
        if abs(stdevp[key] - math.sqrt(varp[key])) > 1e-12 * max(1.0, abs(stdevp[key])):
            found.append(f'R119-4: STDEVP is not the square root of VARP at {key}')
    forecast, forecast_linear = numeric('FORECAST'), numeric('FORECAST.LINEAR')
    for key in sorted(set(forecast) & set(forecast_linear)):
        if abs(forecast[key] - forecast_linear[key]) > 1e-12 * max(1.0, abs(forecast[key])):
            found.append(f'R119-4: FORECAST and FORECAST.LINEAR disagree at {key}')
    for function, a, b, _c, expected in corpus:
        if function != 'MODE' or expected.startswith('#'):
            continue
        values = [float(t) for t in a.split(',') if t not in ('EMPTY', 'TRUE', 'FALSE', '#N/A') and not t.startswith('"')]
        from collections import Counter
        tally = Counter(values)
        top = max(tally.values())
        if top < 2 or abs(float(expected) - min(v for v, k in tally.items() if k == top)) > 1e-12:
            found.append(f'R119-4: MODE({a}) is not a most-frequent value')

    # R119-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R119-5: the committed corpus differs from what tools/gen_r119_legacy_stats_corpus.py renders')

    # R119-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R119-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R119-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 14:
        found.append(f'R119-6: the Kotlin test has {test.count("@Test")} cases; at least 14 are required')
    for helper in HELPERS:
        for arity in helper_arities(test, helper):
            if arity > MAX_HELPER_ARGS:
                found.append(f'R119-6: {helper}(...) is called with {arity} arguments; the helpers take a formula and '
                             f'at most two values')
    if '/r119/legacy_stats_corpus.tsv' not in test:
        found.append('R119-6: the Kotlin test does not read the R119 corpus resource')
    for literal in ('#DIV/0!', '#VALUE!', '#NAME?', '#N/A'):
        if literal not in test:
            found.append(f'R119-6: the Kotlin test never asserts {literal}')

    # R119-7 no regression in the kernels this round reuses.
    for needle in (LEGACY_RANK, MODE_KERNEL, STDEV_KERNEL, A_DISPATCH):
        if needle not in source:
            found.append(f'R119-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[4].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R119_LEGACY_STATS_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
