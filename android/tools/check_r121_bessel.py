#!/usr/bin/env python3
"""R121 gate: `BESSELK` / `BESSELY` (Bessel functions of the second kind).

The product change is small -- dispatch branches for `BESSELK`/`BESSELY` plus the
`bessk`/`bessy` series+asymptotic helpers in `FormulaEval.kt`, and OOXML export
prefixes in `SpillSheetEngine.kt` -- and the ways it can pass review while being
useless are small too: a name dispatched but missing from the corpus, `BESSELK`
returning the wrong sign for x > 10 (the series alone goes negative there), a
corpus generated by the code under test instead of by the documented definitions,
or a fixture edited by hand.

Rules:

  R121-1 registered   `BESSELK` and `BESSELY` are each dispatched exactly once,
                      `bessk` and `bessy` are each defined once, both names are
                      exported with the `_xlfn.` prefix.
  R121-2 covered      every registered name has at least twenty corpus rows and
                      at least five rows that report a refusal (`#NUM!`, `#VALUE!`).
  R121-3 well-formed  no duplicated row, no unknown function, no error literal
                      outside the eight, every argument token parses as a float,
                      every expected value is finite or a literal error.
  R121-4 coherent     the corpus satisfies the documented definitions of the
                      functions, recomputed in the gate from the series/asymptote.
  R121-5 reproducible the committed corpus is byte-identical to what the
                      generator renders.
  R121-6 tested       the Kotlin test declares a tolerance no looser than 1e-12
                      and covers the error cases.
  R121-7 no regression  the `besselSeries` kernel and `BESSELJ`/`BESSELI`
                      dispatch are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI;
this gate decides whether that test would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r121_bessel_corpus import bessk, bessy, render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/R121BesselTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r121/bessel_corpus.tsv'
NAMES = ('BESSELK', 'BESSELY')
FN = {'BESSELK': bessk, 'BESSELY': bessy}
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
HELPERS = ('cell', 'number', 'shown')
MAX_HELPER_ARGS = 3
# Pre-existing kernels this round reuses; their text must survive verbatim.
KEEP = (
    'private fun besselSeries',
    '"BESSELJ", "BESSELI" ->',
)

RULES = {
    'R121-1': 'BESSELK and BESSELY dispatched exactly once; bessk and bessy defined once; both names use the _xlfn. prefix',
    'R121-2': 'every registered name has at least twenty corpus rows and at least five refusal rows',
    'R121-3': 'no duplicated corpus row, no unknown function, no error literal outside the eight',
    'R121-4': 'the corpus satisfies the mathematical definitions of the functions',
    'R121-5': 'the committed corpus is byte-identical to what the generator renders',
    'R121-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R121-7': 'the besselSeries kernel and BESSELJ/BESSELI dispatch are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R121-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R121-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            raise SystemExit(f'R121-3: corpus line {index} is not three columns')
        out.append((parts[0], parts[1], parts[2]))
    return out


def token_parses(token: str) -> bool:
    try:
        float(token)
        return True
    except ValueError:
        return False


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    # BESSELK and BESSELY share one dispatch branch.
    if source.count('"BESSELK", "BESSELY" ->') != 1:
        found.append('R121-1: the BESSELK/BESSELY dispatch branch is not present exactly once')
    for name in NAMES:
        if f'"{name}"' not in source:
            found.append(f'R121-1: {name} does not appear in the product source')
    if source.count('private fun bessk(') != 1:
        found.append('R121-1: bessk is not defined exactly once')
    if source.count('private fun bessy(') != 1:
        found.append('R121-1: bessy is not defined exactly once')
    for name in NAMES:
        if f'"{name}"' not in source:
            found.append(f'R121-1: {name} does not appear in the product source')
    for name in NAMES:
        if f'"{name}"' not in spill:
            found.append(f'R121-1: {name} is missing from the OOXML export prefix list')
    return found


def helper_arities(text: str, helper: str) -> list[int]:
    counts: list[int] = []
    for match in re.finditer(r'\b%s\(' % helper, text):
        depth, commas, index = 0, 0, match.end() - 1
        while index < len(text):
            character = text[index]
            if character == '"':
                index += 1
                while index < len(text) and text[index] != '"':
                    index += 2 if text[index] == '\\' else 1
            elif character == '(':
                depth += 1
            elif character == ')':
                depth -= 1
                if depth == 0:
                    inside = text[match.end():index]
                    counts.append(0 if not inside.strip() else commas + 1)
                    break
            elif character == ',' and depth == 1:
                commas += 1
            index += 1
    return counts


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    counts: dict[str, int] = {name: 0 for name in NAMES}
    refusals: dict[str, int] = {name: 0 for name in NAMES}
    for function, _args, expected in corpus:
        if function not in counts:
            found.append(f'R121-3: corpus names an unregistered function {function}')
            continue
        counts[function] += 1
        if expected.startswith('#'):
            refusals[function] += 1
    for name in NAMES:
        if counts[name] < 20:
            found.append(f'R121-2: {name} has only {counts[name]} rows; at least 20 are required')
        if refusals[name] < 5:
            found.append(f'R121-2: {name} has only {refusals[name]} refusal rows; at least 5 are required')

    seen: set[tuple[str, str]] = set()
    for function, args, expected in corpus:
        key = (function, args)
        if key in seen:
            found.append(f'R121-3: duplicate corpus row {function}({args})')
        seen.add(key)
        for token in args.split(','):
            if token and not token_parses(token):
                found.append(f'R121-3: {function} argument token {token!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R121-3: {function}({args}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R121-3: {function}({args}) expects a non-finite number')

    # R121-4 coherence: spot-check numeric rows against the documented definitions.
    checked = 0
    for function, args, expected in corpus:
        if function not in FN or expected.startswith('#'):
            continue
        x_str, n_str = args.split(',')
        x = float(x_str)
        n = int(float(n_str))
        try:
            want = FN[function](x, n)
        except ValueError:
            continue
        got = float(expected)
        if abs(got - want) > 1e-10 * max(1.0, abs(want)):
            found.append(f'R121-4: {function}({args}) = {got} does not match the definition ({want})')
        checked += 1
    if checked == 0:
        found.append('R121-4: no numeric corpus rows were checked against the definitions')

    # R121-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R121-5: the committed corpus differs from what tools/gen_r121_bessel_corpus.py renders')

    # R121-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R121-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R121-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 14:
        found.append(f'R121-6: the Kotlin test has {test.count("@Test")} cases; at least 14 are required')
    for helper in HELPERS:
        for arity in helper_arities(test, helper):
            if arity > MAX_HELPER_ARGS:
                found.append(f'R121-6: {helper}(...) is called with {arity} arguments; the helpers take a formula and '
                             f'at most two values')
    if '/r121/bessel_corpus.tsv' not in test:
        found.append('R121-6: the Kotlin test does not read the R121 corpus resource')
    for literal in ('#NUM!', '#VALUE!', '#NAME?'):
        if literal not in test:
            found.append(f'R121-6: the Kotlin test never asserts {literal}')

    # R121-7 no regression in the kernels this round reuses.
    for needle in KEEP:
        if needle not in source:
            found.append(f'R121-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[2].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R121_BESSEL_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
