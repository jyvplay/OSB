#!/usr/bin/env python3
"""R120 gate: the distribution inverses, their oracle corpus, and their tests must agree.

The product change is small — dispatch branches for `T.DIST`, `T.DIST.2T`, `T.DIST.RT`, `F.DIST`,
`GAMMALN.PRECISE` and `evalDistInverse`, the `evalTDist` helper, the `evalDistInverse` bisection helper,
and OOXML export prefixes — and the ways such a change can pass review while being useless are small too:
a name dispatched but missing from the corpus, `T.INV` returning the one-tailed instead of the two-tailed
quantile, a right-tailed inverse implemented as left-tailed (the two differ by `1 - p`, so a sign slip
passes a casual test), a corpus generated by the code under test instead of by the documented definitions,
or a fixture edited by hand so the recorded evidence no longer means anything.

Rules:

  R120-1 registered         each of the thirteen names is dispatched exactly once, `evalTDist` and
                            `evalDistInverse` are defined once, `GAMMALN.PRECISE` is dispatched, and all
                            thirteen names are exported with the `_xlfn.` prefix.
  R120-2 covered            every registered name has at least twenty corpus rows and at least five rows
                            that report a refusal (`#NUM!`, `#VALUE!`, `#DIV/0!`, `#N/A`, `#NAME?`).
  R120-3 well-formed        no duplicated row, no unknown function, no error literal outside the eight,
                            every argument token parses as a float, every expected value is finite or a
                            literal error.
  R120-4 coherent           the corpus satisfies the definitions of its own functions, recomputed in the
                            gate: the CDF at each inverse's quantile returns the probability, the two-tailed
                            `T.DIST` is twice the one-tailed tail, and `GAMMALN.PRECISE` is log-gamma at
                            exact points.
  R120-5 reproducible       the committed corpus is byte-identical to what the generator renders.
  R120-6 tested             the Kotlin test declares a tolerance no looser than 1e-12 and covers the error
                            cases.
  R120-7 no regression      the CDF kernels this round reuses (`TDIST.2T`, `TDIST.RT`, `F.DIST.RT`,
                            `incompleteBetaContinuedFraction`, `regGammaLowerP`, `lanczosLnGamma`) are
                            untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI; this gate decides whether
that test would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r120_dist_inverse_corpus import incbeta, gammainc_reg, render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/R120DistInverseTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r120/dist_inverse_corpus.tsv'
NAMES = (
    'GAMMALN.PRECISE', 'T.DIST', 'T.DIST.2T', 'T.DIST.RT', 'F.DIST',
    'T.INV', 'T.INV.2T', 'CHISQ.INV', 'CHISQ.INV.RT', 'F.INV', 'F.INV.RT',
    'BETA.INV', 'GAMMA.INV',
)
DISPATCH = {
    '"T.DIST.2T" -> evalR53ScalarFunction("TDIST.2T", args, env)': 'T.DIST.2T',
    '"T.DIST.RT" -> evalR53ScalarFunction("TDIST.RT", args, env)': 'T.DIST.RT',
    '"F.DIST" -> evalR53ScalarFunction("F.DIST.RT", args, env)': 'F.DIST',
    '-> evalDistInverse(name, args, env)': 'the eight inverses',
}
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
HELPERS = ('cell', 'number', 'shown')
MAX_HELPER_ARGS = 3
# Pre-existing kernels this round reuses; their text must survive verbatim.
KEEP = (
    '"TDIST.2T", "TDIST.RT" ->',
    '"F.DIST.RT" ->',
    'private fun incompleteBetaContinuedFraction',
    'private fun regGammaLowerP',
    'private fun lanczosLnGamma',
)

RULES = {
    'R120-1': 'each of the thirteen names is dispatched exactly once, evalTDist and evalDistInverse are defined once, GAMMALN.PRECISE is dispatched, all thirteen names use the _xlfn. prefix',
    'R120-2': 'every registered name has at least twenty corpus rows and at least five refusal rows',
    'R120-3': 'no duplicated corpus row, no unknown function, no error literal outside the eight',
    'R120-4': 'the corpus satisfies the mathematical definitions of the functions it pins',
    'R120-5': 'the committed corpus is byte-identical to what the generator renders',
    'R120-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R120-7': 'the CDF kernels this round reuses are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R120-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R120-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            raise SystemExit(f'R120-3: corpus line {index} is not three columns')
        out.append((parts[0], parts[1], parts[2]))
    return out


def token_parses(token: str) -> bool:
    try:
        float(token)
        return True
    except ValueError:
        return False


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    for dispatch, name in DISPATCH.items():
        if source.count(dispatch) != 1:
            found.append(f'R120-1: the dispatch for {name} is not present exactly once: {dispatch[:60]}')
    if source.count('private fun evalTDist') != 1:
        found.append('R120-1: evalTDist is not defined exactly once')
    if source.count('private fun evalDistInverse') != 1:
        found.append('R120-1: evalDistInverse is not defined exactly once')
    if source.count('"GAMMALN.PRECISE" -> {') != 1:
        found.append('R120-1: GAMMALN.PRECISE is not dispatched exactly once')
    for name in NAMES:
        if f'"{name}"' not in source:
            found.append(f'R120-1: {name} does not appear in the product source')
    for name in NAMES:
        if f'"{name}"' not in spill:
            found.append(f'R120-1: {name} is missing from the OOXML export prefix list')
    return found


def helper_arities(text: str, helper: str) -> list[int]:
    """Top-level argument counts of every `helper(...)` call, so a test cannot pass a Kotlin arity error to CI."""
    counts: list[int] = []
    for match in re.finditer(r'\b%s\(' % helper, text):
        depth, commas, index = 0, 0, match.end() - 1
        while index < len(text):
            character = text[index]
            if character == '"':
                index += 1
                while index < len(text) and text[index] != '"':
                    index += 2 if text[index] == '\\' else 1
            elif character == '(':
                depth += 1
            elif character == ')':
                depth -= 1
                if depth == 0:
                    inside = text[match.end():index]
                    counts.append(0 if not inside.strip() else commas + 1)
                    break
            elif character == ',' and depth == 1:
                commas += 1
            index += 1
    return counts


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    # R120-2 coverage.
    counts: dict[str, int] = {name: 0 for name in NAMES}
    refusals: dict[str, int] = {name: 0 for name in NAMES}
    for function, _args, expected in corpus:
        if function not in counts:
            found.append(f'R120-3: corpus names an unregistered function {function}')
            continue
        counts[function] += 1
        if expected.startswith('#'):
            refusals[function] += 1
    for name in NAMES:
        if counts[name] < 20:
            found.append(f'R120-2: {name} has only {counts[name]} rows; at least 20 are required')
        if refusals[name] < 5:
            found.append(f'R120-2: {name} has only {refusals[name]} refusal rows; at least 5 are required')

    # R120-3 shape.
    seen: set[tuple[str, str]] = set()
    for function, args, expected in corpus:
        key = (function, args)
        if key in seen:
            found.append(f'R120-3: duplicate corpus row {function}({args})')
        seen.add(key)
        for token in args.split(','):
            if token and not token_parses(token):
                found.append(f'R120-3: {function} argument token {token!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R120-3: {function}({args}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R120-3: {function}({args}) expects a non-finite number')

    # R120-4 coherence, recomputed in the gate from the definitions.
    def cdf(name: str, args: list[float]) -> float:
        if name == 'T.DIST.2T':
            return incbeta(args[1] / 2.0, 0.5, args[1] / (args[1] + args[0] * args[0]))
        if name == 'T.DIST.RT':
            ib = incbeta(args[1] / 2.0, 0.5, args[1] / (args[1] + args[0] * args[0]))
            return 0.5 * ib if args[0] >= 0.0 else 1.0 - 0.5 * ib
        if name == 'F.DIST':
            u = (args[1] * args[0]) / (args[1] * args[0] + args[2])
            return incbeta(args[1] / 2.0, args[2] / 2.0, u)
        if name == 'CHISQ.DIST':
            return gammainc_reg(args[1] / 2.0, args[0] / 2.0)
        if name == 'BETA.DIST':
            return incbeta(args[1], args[2], args[0])
        if name == 'GAMMA.DIST':
            return gammainc_reg(args[1], args[0] / args[2])
        raise AssertionError(name)

    for function, args, expected in corpus:
        if function in ('CHISQ.INV', 'CHISQ.INV.RT', 'F.INV', 'F.INV.RT', 'BETA.INV', 'GAMMA.INV',
                        'T.INV', 'T.INV.2T') and not expected.startswith('#'):
            p = float(args.split(',')[0])
            x = float(expected)
            if function in ('CHISQ.INV', 'F.INV', 'BETA.INV', 'GAMMA.INV', 'T.INV'):
                cdf_name = {'CHISQ.INV': 'CHISQ.DIST', 'F.INV': 'F.DIST', 'BETA.INV': 'BETA.DIST',
                            'GAMMA.INV': 'GAMMA.DIST', 'T.INV': 'T.DIST.2T'}[function]
                got = cdf(cdf_name, [x] + [float(t) for t in args.split(',')[1:]])
                if abs(got - p) > 1e-10 * max(1.0, abs(p)):
                    found.append(f'R120-4: {function}({args}) = {x} does not invert its CDF (got {got}, want {p})')
            elif function in ('CHISQ.INV.RT', 'F.INV.RT'):
                cdf_name = 'CHISQ.DIST' if function == 'CHISQ.INV.RT' else 'F.DIST'
                got = cdf(cdf_name, [x] + [float(t) for t in args.split(',')[1:]])
                if abs(got - (1.0 - p)) > 1e-10 * max(1.0, abs(p)):
                    found.append(f'R120-4: {function}({args}) = {x} does not invert its right tail (got {got}, want {1 - p})')
    # T.DIST tail relation: tails==2 is twice tails==1 (for x >= 0), and T.DIST(-x, df, 1) = 1 - T.DIST(x, df, 1).
    for function, args, expected in corpus:
        if function != 'T.DIST' or expected.startswith('#'):
            continue
        x, df, tails = (float(t) for t in args.split(','))
        if tails == 1.0 and x > 0.0:
            twin = [r for r in corpus if r[0] == 'T.DIST' and r[1] == f'{x},{df},2.0']
            if twin:
                want = float(twin[0][2])
                if abs(float(expected) * 2.0 - want) > 1e-12 * max(1.0, abs(want)):
                    found.append(f'R120-4: T.DIST({x},{df},2) is not twice T.DIST({x},{df},1)')
        if tails == 1.0 and x > 0.0:
            neg = [r for r in corpus if r[0] == 'T.DIST' and r[1] == f'{-x},{df},1.0']
            if neg:
                if abs(float(expected) + float(neg[0][2]) - 1.0) > 1e-12:
                    found.append(f'R120-4: T.DIST(-{x},{df},1) is not 1 - T.DIST({x},{df},1)')
    # GAMMALN.PRECISE at exact points.
    for function, args, expected in corpus:
        if function != 'GAMMALN.PRECISE' or expected.startswith('#'):
            continue
        x = float(args)
        if x in (1.0, 2.0):
            if abs(float(expected)) > 1e-12:
                found.append(f'R120-4: GAMMALN.PRECISE({x}) is not 0')
        if x == 3.0 and abs(float(expected) - math.log(2.0)) > 1e-12:
            found.append(f'R120-4: GAMMALN.PRECISE(3) is not ln(2)')

    # R120-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R120-5: the committed corpus differs from what tools/gen_r120_dist_inverse_corpus.py renders')

    # R120-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R120-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R120-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 14:
        found.append(f'R120-6: the Kotlin test has {test.count("@Test")} cases; at least 14 are required')
    for helper in HELPERS:
        for arity in helper_arities(test, helper):
            if arity > MAX_HELPER_ARGS:
                found.append(f'R120-6: {helper}(...) is called with {arity} arguments; the helpers take a formula and '
                             f'at most two values')
    if '/r120/dist_inverse_corpus.tsv' not in test:
        found.append('R120-6: the Kotlin test does not read the R120 corpus resource')
    for literal in ('#NUM!', '#VALUE!', '#NAME?'):
        if literal not in test:
            found.append(f'R120-6: the Kotlin test never asserts {literal}')

    # R120-7 no regression in the kernels this round reuses.
    for needle in KEEP:
        if needle not in source:
            found.append(f'R120-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[2].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R120_DIST_INVERSE_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
