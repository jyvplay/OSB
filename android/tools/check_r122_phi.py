#!/usr/bin/env python3
"""R122 gate: `PHI` / `DELTA` / `GESTEP` (standard normal PDF and engineering comparisons).

The product change is small -- dispatch branches for `PHI`/`DELTA`/`GESTEP` plus the
`phi`/`delta`/`gestep` helpers in `FormulaEval.kt`, and OOXML export prefixes in
`SpillSheetEngine.kt` -- and the ways it can pass review while being useless are small
too: a name dispatched but missing from the corpus, `DELTA` returning the wrong value
for equal inputs, `GESTEP` missing the default step argument, or a corpus generated by
the code under test instead of by the documented definitions.

Rules:

  R122-1 registered   `PHI`, `DELTA` and `GESTEP` are each dispatched exactly once,
                      `phi`, `delta` and `gestep` are each defined once, all three names
                      are exported with the `_xlfn.` prefix.
  R122-2 covered      every registered name has at least twenty corpus rows and
                      at least five rows that report a refusal (`#NUM!`, `#VALUE!`).
  R122-3 well-formed  no duplicated row, no unknown function, no error literal
                      outside the eight, every argument token parses as a float,
                      every expected value is finite or a literal error.
  R122-4 coherent     the corpus satisfies the documented definitions of the
                      functions, recomputed in the gate from the series/asymptote.
  R122-5 reproducible the committed corpus is byte-identical to what the
                      generator renders.
  R122-6 tested       the Kotlin test declares a tolerance no looser than 1e-12
                      and covers the error cases.
  R122-7 no regression  the `besselSeries` kernel and `BESSELJ`/`BESSELI`/`BESSELK`/
                      `BESSELY` dispatch are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI;
this gate decides whether that test would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r122_phi_corpus import phi, delta, gestep, render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/R122PhiTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r122/phi_corpus.tsv'
NAMES = ('PHI', 'DELTA', 'GESTEP')
FN = {'PHI': lambda args: phi(float(args[0])),
      'DELTA': lambda args: delta(float(args[0]), float(args[1])),
      'GESTEP': lambda args: gestep(float(args[0]), float(args[1]) if len(args) > 1 else 0.0)}
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
MAX_HELPER_ARGS = 3
KEEP = (
    'private fun besselSeries',
    '"BESSELJ", "BESSELI" ->',
    '"BESSELK", "BESSELY" ->',
)

RULES = {
    'R122-1': 'PHI, DELTA and GESTEP dispatched exactly once; phi, delta and gestep defined once; all names use the _xlfn. prefix',
    'R122-2': 'every registered name has at least twenty corpus rows and at least five refusal rows',
    'R122-3': 'no duplicated corpus row, no unknown function, no error literal outside the eight',
    'R122-4': 'the corpus satisfies the mathematical definitions of the functions',
    'R122-5': 'the committed corpus is byte-identical to what the generator renders',
    'R122-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R122-7': 'the besselSeries kernel and BESSELJ/BESSELI/BESSELK/BESSELY dispatch are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R122-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R122-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            raise SystemExit(f'R122-3: corpus line {index} is not three columns')
        out.append((parts[0], parts[1], parts[2]))
    return out


def token_parses(token: str) -> bool:
    try:
        float(token)
        return True
    except ValueError:
        return False


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    for name in NAMES:
        if source.count(f'"{name}",') != 1 and source.count(f'"{name}" ->') != 1:
            found.append(f'R122-1: the dispatch for {name} is not present exactly once')
    if source.count('private fun phi(') != 1:
        found.append('R122-1: phi is not defined exactly once')
    if source.count('private fun delta(') != 1:
        found.append('R122-1: delta is not defined exactly once')
    if source.count('private fun gestep(') != 1:
        found.append('R122-1: gestep is not defined exactly once')
    for name in NAMES:
        if f'"{name}"' not in spill:
            found.append(f'R122-1: {name} is missing from the OOXML export prefix list')
    return found


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    counts: dict[str, int] = {name: 0 for name in NAMES}
    refusals: dict[str, int] = {name: 0 for name in NAMES}
    for function, _args, expected in corpus:
        if function not in counts:
            found.append(f'R122-3: corpus names an unregistered function {function}')
            continue
        counts[function] += 1
        if expected.startswith('#'):
            refusals[function] += 1
    for name in NAMES:
        if counts[name] < 20:
            found.append(f'R122-2: {name} has only {counts[name]} rows; at least 20 are required')
        if refusals[name] < 5:
            found.append(f'R122-2: {name} has only {refusals[name]} refusal rows; at least 5 are required')

    seen: set[tuple[str, str]] = set()
    for function, args, expected in corpus:
        key = (function, args)
        if key in seen:
            found.append(f'R122-3: duplicate corpus row {function}({args})')
        seen.add(key)
        for token in args.split(','):
            if token and not token_parses(token):
                found.append(f'R122-3: {function} argument token {token!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R122-3: {function}({args}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R122-3: {function}({args}) expects a non-finite number')

    # R122-4 coherence: check numeric rows against the documented definitions.
    checked = 0
    for function, args, expected in corpus:
        if function not in FN or expected.startswith('#'):
            continue
        arg_list = args.split(',')
        try:
            want = FN[function](arg_list)
        except ValueError:
            continue
        got = float(expected)
        if abs(got - want) > 1e-10 * max(1.0, abs(want)):
            found.append(f'R122-4: {function}({args}) = {got} does not match the definition ({want})')
        checked += 1
    if checked == 0:
        found.append('R122-4: no numeric corpus rows were checked against the definitions')

    # R122-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R122-5: the committed corpus differs from what tools/gen_r122_phi_corpus.py renders')

    # R122-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R122-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R122-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 10:
        found.append(f'R122-6: the Kotlin test has {test.count("@Test")} cases; at least 10 are required')
    if '/r122/phi_corpus.tsv' not in test:
        found.append('R122-6: the Kotlin test does not read the R122 corpus resource')
    for literal in ('#NUM!', '#VALUE!', '#NAME?'):
        if literal not in test:
            found.append(f'R122-6: the Kotlin test never asserts {literal}')

    # R122-7 no regression in the kernels this round reuses.
    for needle in KEEP:
        if needle not in source:
            found.append(f'R122-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[2].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R122_PHI_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
