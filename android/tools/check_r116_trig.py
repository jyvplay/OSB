#!/usr/bin/env python3
"""R116 gate: the trigonometry a formula can reach, its oracle corpus, and its tests must agree.

The product change is small — fourteen names added to one dispatch branch plus one helper in `FormulaEval.kt` — and the
way such a change can pass review while being useless is equally small: a name added to the helper but not to the
dispatch, a corpus row generated by the code under test instead of by an independent one, a tolerance quietly raised
until a wrong result fits, or a fixture edited by hand so the recorded evidence no longer means anything.

Rules:

  R116-1 registered         each of the fourteen names is dispatched and implemented exactly once.
  R116-2 covered            every registered name has corpus rows, and PI has exactly one no-argument row.
  R116-3 well-formed        no duplicated row, no unknown function, no error literal outside the seven.
  R116-4 coherent           the corpus satisfies the mathematical identities of its own functions.
  R116-5 reproducible       the committed corpus is byte-identical to what the generator renders.
  R116-6 tested             the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases.
  R116-7 no regression      the pre-existing reciprocal kernels and their ACOT definition are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI; this gate decides whether that test
would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r116_trig_corpus import render

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/TrigFunctionTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r116/trig_corpus.tsv'
NAMES = ('SIN', 'COS', 'TAN', 'ASIN', 'ACOS', 'ATAN', 'ATAN2', 'SINH', 'COSH', 'TANH',
         'ASINH', 'ACOSH', 'ATANH', 'PI')
DISPATCH_CALL = 'evalR116TrigFunction(name, args, env)'
DISPATCH_WINDOW = 420
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
HELPERS = ('cell', 'number', 'shown')
MAX_HELPER_ARGS = 3
ACOT_DEFINITION = '"ACOT" -> (Math.PI / 2.0) - kotlin.math.atan(x)'
RECIPROCALS = ('"SEC", "CSC", "COT", "SECH", "CSCH", "COTH", "ACOT", "ACOTH",')

RULES = {
    'R116-1': 'each of the fourteen trigonometry names is dispatched and implemented exactly once',
    'R116-2': 'every registered name has corpus rows, and PI has exactly one no-argument row',
    'R116-3': 'no duplicated corpus row, no unknown function, no error literal outside the seven',
    'R116-4': 'the corpus satisfies the mathematical identities of the functions it pins',
    'R116-5': 'the committed corpus is byte-identical to what the generator renders',
    'R116-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R116-7': 'the pre-existing reciprocal kernels and their ACOT definition are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R116-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R116-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 4:
            raise SystemExit(f'R116-3: corpus line {index} is not four columns')
        out.append((parts[0], parts[1], parts[2], parts[3]))
    return out


def values(rows_: list[tuple[str, str, str, str]], name: str) -> dict[float, float]:
    out: dict[float, float] = {}
    for function, x, _y, expected in rows_:
        if function != name or expected.startswith('#') or not x:
            continue
        out[float(x)] = float(expected)
    return out


def registered(source: str) -> list[str]:
    """Each name must appear in the R116 dispatch branch and have exactly one implementation branch."""
    found: list[str] = []
    if source.count(DISPATCH_CALL) != 1 or 'private fun evalR116TrigFunction' not in source:
        found.append(f'R116-1: the R116 dispatch call and its definition are not present exactly once')
        return found
    call = source.index(DISPATCH_CALL)
    window = source[max(0, call - DISPATCH_WINDOW):call]
    body_start = source.index('private fun evalR116TrigFunction')
    body_end = source.index('private class Parser(', body_start)
    body = source[body_start:body_end]
    for name in NAMES:
        if f'"{name}"' not in window:
            found.append(f'R116-1: {name} is not in the R116 dispatch branch')
        branches = len(re.findall(r'"%s"\s*->' % re.escape(name), body))
        if name == 'PI':
            if 'if (name == "PI")' not in body:
                found.append('R116-1: PI has no implementation branch in the R116 helper')
        elif name == 'ATAN2':
            if branches != 1 or 'if (name == "ATAN2") 2 else 1' not in body:
                found.append('R116-1: ATAN2 must have one branch and declare arity two')
        elif branches != 1:
            found.append(f'R116-1: {name} has {branches} implementation branches; expected exactly one')
    return found


def helper_arities(text: str, helper: str) -> list[int]:
    """Top-level argument counts of every `helper(...)` call, so a test cannot pass a Kotlin arity error to CI."""
    counts: list[int] = []
    for match in re.finditer(r'\b%s\(' % helper, text):
        depth, commas, index = 0, 0, match.end() - 1
        while index < len(text):
            character = text[index]
            if character == '"':
                index += 1
                while index < len(text) and text[index] != '"':
                    index += 2 if text[index] == '\\' else 1
            elif character == '(':
                depth += 1
            elif character == ')':
                depth -= 1
                if depth == 0:
                    counts.append(commas + 1 if text[match.end():index].strip() or commas else 0)
                    break
            elif character == ',' and depth == 1:
                commas += 1
            index += 1
    return counts


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source)

    # R116-2 coverage.
    counts: dict[str, int] = {}
    for function, _x, _y, _expected in corpus:
        counts[function] = counts.get(function, 0) + 1
    for name in NAMES:
        if counts.get(name, 0) == 0:
            found.append(f'R116-2: no corpus row for {name}')
    if counts.get('PI', 0) != 1:
        found.append(f'R116-2: PI must have exactly one row, found {counts.get("PI", 0)}')
    else:
        pi_row = next(row for row in corpus if row[0] == 'PI')
        if pi_row[1] or pi_row[2]:
            found.append('R116-2: the PI row must pass no arguments')
    for name in ('SIN', 'COS', 'TAN', 'ASIN', 'ACOS', 'ATAN', 'SINH', 'COSH', 'TANH', 'ASINH', 'ACOSH', 'ATANH'):
        if counts.get(name, 0) < 20:
            found.append(f'R116-2: {name} has only {counts.get(name, 0)} rows; at least 20 are required')
    if counts.get('ATAN2', 0) < 10:
        found.append(f'R116-2: ATAN2 has only {counts.get("ATAN2", 0)} rows; at least 10 are required')

    # R116-3 shape.
    seen: set[tuple[str, str, str]] = set()
    for function, x, y, expected in corpus:
        key = (function, x, y)
        if key in seen:
            found.append(f'R116-3: duplicate corpus row {function}({x}, {y})')
        seen.add(key)
        if function not in NAMES:
            found.append(f'R116-3: corpus names an unregistered function {function}')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R116-3: {function}({x}, {y}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R116-3: {function}({x}, {y}) expects a non-finite number')

    # R116-4 coherence, recomputed from the corpus itself.
    sin, cos, tan = values(corpus, 'SIN'), values(corpus, 'COS'), values(corpus, 'TAN')
    for x in sorted(set(sin) & set(cos)):
        if abs(sin[x] ** 2 + cos[x] ** 2 - 1.0) > 1e-12:
            found.append(f'R116-4: sin^2+cos^2 != 1 at {x}')
    asin, acos = values(corpus, 'ASIN'), values(corpus, 'ACOS')
    for x in sorted(set(asin) & set(acos)):
        if abs(asin[x] + acos[x] - math.pi / 2.0) > 1e-12:
            found.append(f'R116-4: asin+acos != pi/2 at {x}')
    for x in sorted(sin):
        if -x in sin and abs(sin[-x] + sin[x]) > 1e-12:
            found.append(f'R116-4: SIN is not odd at {x}')
    for x in sorted(cos):
        if -x in cos and abs(cos[-x] - cos[x]) > 1e-12:
            found.append(f'R116-4: COS is not even at {x}')
    atan, asinh = values(corpus, 'ATAN'), values(corpus, 'ASINH')
    for x in sorted(atan):
        if -x in atan and abs(atan[-x] + atan[x]) > 1e-12:
            found.append(f'R116-4: ATAN is not odd at {x}')
    for x in sorted(asinh):
        if -x in asinh and abs(asinh[-x] + asinh[x]) > 1e-12:
            found.append(f'R116-4: ASINH is not odd at {x}')
    sinh, cosh, tanh = values(corpus, 'SINH'), values(corpus, 'COSH'), values(corpus, 'TANH')
    for x in sorted(set(sinh) & set(cosh)):
        if abs((cosh[x] - sinh[x]) - math.exp(-x)) > 1e-12 * cosh[x]:
            found.append(f'R116-4: cosh-sinh != exp(-x) at {x}')
        if abs(x) <= 4.0 and abs(cosh[x] ** 2 - sinh[x] ** 2 - 1.0) > 1e-10:
            found.append(f'R116-4: cosh^2-sinh^2 != 1 at {x}')
    for x, y in tanh.items():
        if abs(y) > 1.0 or abs(y - math.tanh(x)) > 1e-12:
            found.append(f'R116-4: TANH({x}) is not the hyperbolic tangent or leaves [-1, 1]')
    atan2: dict[tuple[str, str], float] = {}
    for function, x, y, expected in corpus:
        if function == 'ATAN2' and not expected.startswith('#'):
            atan2[(x, y)] = float(expected)
    for (x, y), value in atan2.items():
        xv, yv = float(x), float(y)
        if abs(value - math.atan2(yv, xv)) > 1e-12:
            found.append(f'R116-4: ATAN2({x}, {y}) is not atan2(y, x)')
    for function, x, _y, expected in corpus:
        if function == 'ATAN2' and expected.startswith('#'):
            if not (float(x) == 0.0 and expected == '#DIV/0!'):
                found.append(f'R116-4: ATAN2({x}) declares {expected}, which is not the documented refusal')
    if 'PI' in counts:
        pi_value = next(float(row[3]) for row in corpus if row[0] == 'PI')
        if pi_value != math.pi:
            found.append('R116-4: the PI row is not the double nearest to pi')

    # R116-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R116-5: the committed corpus differs from what tools/gen_r116_trig_corpus.py renders')

    # R116-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R116-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R116-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 14:
        found.append(f'R116-6: the Kotlin test has {test.count("@Test")} cases; at least 14 are required')
    for helper in HELPERS:
        for arity in helper_arities(test, helper):
            if arity > MAX_HELPER_ARGS:
                found.append(f'R116-6: {helper}(...) is called with {arity} arguments; the helpers take a formula and '
                             f'at most two values')
    if '/r116/trig_corpus.tsv' not in test:
        found.append('R116-6: the Kotlin test does not read the R116 corpus resource')
    for literal in ('#NUM!', '#DIV/0!', '#VALUE!', '#NAME?'):
        if literal not in test:
            found.append(f'R116-6: the Kotlin test never asserts {literal}')

    # R116-7 no regression in the kernels this round reuses.
    for needle in (RECIPROCALS, ACOT_DEFINITION):
        if needle not in source:
            found.append(f'R116-7: the pre-existing reciprocal kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[3].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R116_TRIG_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
