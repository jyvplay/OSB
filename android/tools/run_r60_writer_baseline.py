#!/usr/bin/env python3
"""Compare current default formatted DOCX bytes against the pinned preceding OSB implementation."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
BASELINE = 'ab4840b27b6d5f9cf19526461551f4e6efe696b0'
sys.path.insert(0, str(ROOT / 'tools'))
import bootstrap_host_tools


def source(i):
    return '\n'.join((f'1. item-{i} **bold** α😀', f'1. second-{i}\tend', f'plain-{i}', '1. later',
                      '- bullet', '2. literal', '01. literal', '1. ', '  1. nested', '# heading', ''))


def main():
    env = bootstrap_host_tools.environment(Path.home() / '.cache/fusion-host-r23')
    out = ROOT / 'testing/build/r60writer/legacy'
    out.mkdir(parents=True, exist_ok=True)
    old = out / 'StructuredWriterDocx.kt'
    result = subprocess.run(['git', 'show', f'{BASELINE}:android/format/ooxml/src/main/kotlin/dev/fusion/ooxml/StructuredWriterDocx.kt'],
                            cwd=ROOT, capture_output=True, check=True)
    old.write_bytes(result.stdout)
    ooxml = ROOT / 'format/ooxml/src/main/kotlin/dev/fusion/ooxml'
    names = ('BoundedXml', 'ColLetters', 'SheetRange', 'CellErr', 'FormulaEval', 'NumberFormatRender', 'NumFmtSections', 'FormulaXlsx',
             'DocxNumbering', 'DocxPackage', 'OfficeSheetDraft', 'PlainWriterDocx')
    sources = [ooxml / (name + '.kt') for name in names] + [old, ROOT / 'testing/src/r60writer/kotlin/dev/fusion/testing/R60WriterLegacyProbe.kt']
    jar = out / 'legacy.jar'
    jar.unlink(missing_ok=True)
    subprocess.run([env['KOTLINC'], '-jvm-target', '17', '-Werror', '-include-runtime', *map(str, sources), '-d', str(jar)],
                   env=env, check=True)
    paths = []
    for i in range(128):
        path = out / f'{i:03}.txt'
        path.write_text(source(i), encoding='utf-8', newline='')
        paths.append(path)
    proc = subprocess.run([str(Path(env['JAVA_HOME']) / 'bin/java'), '-Dfile.encoding=UTF-8', '-cp', str(jar),
                           'dev.fusion.testing.R60WriterLegacyProbe'], input=''.join(str(p) + '\n' for p in paths),
                          text=True, capture_output=True, check=True, env=env, timeout=120)
    hashes = proc.stdout.splitlines()
    if len(hashes) != len(paths):
        raise ValueError('Missing or extra legacy results')
    for i, digest in enumerate(hashes):
        current = ROOT / f'testing/build/r60writer/artifacts/doc-{i:03}-default.docx'
        if hashlib.sha256(current.read_bytes()).hexdigest() != digest:
            raise ValueError(f'Old/default DOCX bytes differ at {i}')
    report = {'baseline': BASELINE, 'legacy_source_sha256': hashlib.sha256(result.stdout).hexdigest(),
              'cases': len(hashes), 'scope': 'Exact generated bytes on a finite corpus, not all-input or rendering proof.'}
    (out / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
