#!/usr/bin/env python3
"""R123 gate: `CHISQ.TEST` / `F.TEST` / `Z.TEST` / `T.TEST` / `SKEW.P` statistical test functions.

The product change is small -- dispatch branches for five names plus the `chisqTest`/`fTest`/
`zTest`/`tTest`/`skewP` helpers in `FormulaEval.kt`, and OOXML export prefixes in
`SpillSheetEngine.kt` -- and the ways it can pass review while being useless are small too:
a name dispatched but missing from the corpus, `F.TEST` returning the wrong tail (one-tailed
instead of two-tailed), `CHISQ.TEST` with zero expected values not refused, or a corpus
generated by the code under test instead of by the documented definitions.

Rules:

  R123-1 registered   CHISQ.TEST, F.TEST, Z.TEST, T.TEST and SKEW.P are each dispatched exactly
                      once, chisqTest/fTest/zTest/tTest/skewP are each defined once, all five
                      names are exported with the `_xlfn.` prefix.
  R123-2 covered      every registered name has at least twenty corpus rows and at least five
                      rows that report a refusal (`#NUM!`, `#VALUE!`).
  R123-3 well-formed  no duplicated row, no unknown function, no error literal outside the
                      eight, every argument token parses as a float, every expected value is
                      finite or a literal error.
  R123-4 coherent     the corpus satisfies the documented definitions of the functions,
                      recomputed in the gate from the statistical formulas.
  R123-5 reproducible the committed corpus is byte-identical to what the generator renders.
  R123-6 tested       the Kotlin test declares a tolerance no looser than 1e-12 and covers the
                      error cases.
  R123-7 no regression  the `besselSeries` kernel and `BESSELJ`/`BESSELI`/`BESSELK`/`BESSELY`
                      dispatch are untouched.

Nothing here executes Kotlin. The Kotlin evidence is `:format:ooxml:test` in CI;
this gate decides whether that test would be measuring anything.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

from gen_r123_stat_test_corpus import (
    chisqTest, fTest, zTest, tTest, skewP, render,
)

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/FormulaEval.kt'
SPILL = 'format/ooxml/src/main/kotlin/dev/fusion/ooxml/SpillSheetEngine.kt'
TEST = 'format/ooxml/src/test/kotlin/dev/fusion/ooxml/R123StatTest.kt'
CORPUS = 'format/ooxml/src/test/resources/r123/stat_test_corpus.tsv'
NAMES = ('CHISQ.TEST', 'F.TEST', 'Z.TEST', 'T.TEST', 'SKEW.P')
LITERALS = {'#NULL!', '#DIV/0!', '#VALUE!', '#REF!', '#NAME?', '#NUM!', '#N/A'}
TOLERANCE_CEILING = 1e-12
MAX_HELPER_ARGS = 3
KEEP = (
    'private fun besselSeries',
    '"BESSELJ", "BESSELI" ->',
    '"BESSELK", "BESSELY" ->',
)

RULES = {
    'R123-1': 'CHISQ.TEST, F.TEST, Z.TEST, T.TEST and SKEW.P dispatched exactly once; helpers defined once; all names use the _xlfn. prefix',
    'R123-2': 'every registered name has at least twenty corpus rows and at least five refusal rows',
    'R123-3': 'no duplicated corpus row, no unknown function, no error literal outside the eight',
    'R123-4': 'the corpus satisfies the mathematical definitions of the functions',
    'R123-5': 'the committed corpus is byte-identical to what the generator renders',
    'R123-6': 'the Kotlin test declares a tolerance no looser than 1e-12 and covers the error cases',
    'R123-7': 'the besselSeries kernel and BESSELJ/BESSELI/BESSELK/BESSELY dispatch are untouched',
}


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise SystemExit(f'R123-0: missing {relative}')
    return path.read_text(encoding='utf-8')


def rows(root: Path) -> list[tuple[str, str, str]]:
    lines = read(root, CORPUS).splitlines()
    if not lines or not lines[0].startswith('function'):
        raise SystemExit(f'R123-3: {CORPUS} has no header row')
    out: list[tuple[str, str, str]] = []
    for index, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            raise SystemExit(f'R123-3: corpus line {index} is not three columns')
        out.append((parts[0], parts[1], parts[2]))
    return out


def token_parses(token: str) -> bool:
    try:
        float(token)
        return True
    except ValueError:
        return False


def registered(source: str, spill: str) -> list[str]:
    found: list[str] = []
    for name in NAMES:
        if source.count(f'"{name}",') != 1 and source.count(f'"{name}" ->') != 1:
            found.append(f'R123-1: the dispatch for {name} is not present exactly once')
    for helper in ('chisqTest', 'fTest', 'zTest', 'tTest', 'skewP'):
        if source.count(f'private fun {helper}(') != 1:
            found.append(f'R123-1: {helper} is not defined exactly once')
    for name in NAMES:
        if f'"{name}"' not in spill:
            found.append(f'R123-1: {name} is missing from the OOXML export prefix list')
    return found


def violations(root: Path = DEFAULT_ROOT) -> tuple[list[str], dict]:
    source = read(root, SOURCE)
    spill = read(root, SPILL)
    test = (root / TEST).read_text(encoding='utf-8') if (root / TEST).is_file() else ''
    corpus = rows(root)
    found = registered(source, spill)

    counts: dict[str, int] = {name: 0 for name in NAMES}
    refusals: dict[str, int] = {name: 0 for name in NAMES}
    for function, _args, expected in corpus:
        if function not in counts:
            found.append(f'R123-3: corpus names an unregistered function {function}')
            continue
        counts[function] += 1
        if expected.startswith('#'):
            refusals[function] += 1
    for name in NAMES:
        if counts[name] < 20:
            found.append(f'R123-2: {name} has only {counts[name]} rows; at least 20 are required')
        if refusals[name] < 5:
            found.append(f'R123-2: {name} has only {refusals[name]} refusal rows; at least 5 are required')

    seen: set[tuple[str, str]] = set()
    for function, args, expected in corpus:
        key = (function, args)
        if key in seen:
            found.append(f'R123-3: duplicate corpus row {function}({args})')
        seen.add(key)
        # Only check numeric tokens for well-formedness; array literals use {};: syntax
        # whose internal semicolons are row separators, not argument separators.
        if '{' not in args and '}' not in args:
            for token in args.split(','):
                if token and not token_parses(token):
                    found.append(f'R123-3: {function} argument token {token!r} does not parse')
        if expected.startswith('#'):
            if expected not in LITERALS:
                found.append(f'R123-3: {function}({args}) expects the non-literal {expected}')
        else:
            value = float(expected)
            if value != value or value in (math.inf, -math.inf):
                found.append(f'R123-3: {function}({args}) expects a non-finite number')

    # R123-4 coherence: check numeric rows against the documented definitions.
    checked = 0
    for function, args, expected in corpus:
        if function not in ('CHISQ.TEST', 'F.TEST', 'Z.TEST', 'T.TEST', 'SKEW.P') or expected.startswith('#'):
            continue
        arg_list = args.split(',')
        try:
            if function == 'CHISQ.TEST':
                # Parse array literals {a,b;c,d}
                parts = args.split('},')
                actual_str = parts[0].lstrip('{')
                expected_str = parts[1].rstrip('}')
                def parse_grid(s: str) -> list[list[float]]:
                    return [[float(v) for v in row.split(',')] for row in s.split(';')]
                want = chisqTest(parse_grid(actual_str), parse_grid(expected_str))
            elif function == 'F.TEST':
                parts = args.split('},{')
                xs = [float(v) for v in parts[0].lstrip('{').split(',')]
                ys = [float(v) for v in parts[1].rstrip('}').split(',')]
                want = fTest(xs, ys)
            elif function == 'Z.TEST':
                # {x1,x2,...},mu[,sigma]
                brace_end = args.index('}')
                xs = [float(v) for v in args[1:brace_end].split(',')]
                rest = args[brace_end + 1:].lstrip(',').split(',')
                mu = float(rest[0])
                sigma = float(rest[1]) if len(rest) > 1 else None
                want = zTest(xs, mu, sigma)
            elif function == 'T.TEST':
                # {x1,...},{y1,...},tails,type
                brace_end = args.index('},')
                xs = [float(v) for v in args[1:brace_end].split(',')]
                rest = args[brace_end + 2:].split(',')
                ys = [float(v) for v in rest[0].rstrip('}').split(',')]
                tails = float(rest[1])
                type_ = float(rest[2])
                want = tTest(xs, ys, tails, type_)
            else:  # SKEW.P
                nums = [float(v) for v in args.split(',')]
                want = skewP(nums)
        except Exception:
            continue
        got = float(expected)
        if math.isnan(want):
            continue
        if abs(got - want) > 1e-10 * max(1.0, abs(want)):
            found.append(f'R123-4: {function}({args}) = {got} does not match the definition ({want})')
        checked += 1
    if checked == 0:
        found.append('R123-4: no numeric corpus rows were checked against the definitions')

    # R123-5 generator fidelity.
    committed = (root / CORPUS).read_text(encoding='utf-8') if (root / CORPUS).is_file() else ''
    if committed != render():
        found.append('R123-5: the committed corpus differs from what tools/gen_r123_stat_test_corpus.py renders')

    # R123-6 test discipline.
    tolerance = re.search(r'private val TOL = ([0-9.eE+-]+)', test)
    if tolerance is None:
        found.append('R123-6: the Kotlin test does not declare TOL')
    elif float(tolerance.group(1)) > TOLERANCE_CEILING:
        found.append(f'R123-6: TOL was loosened to {tolerance.group(1)}, above {TOLERANCE_CEILING:g}')
    if test.count('@Test') < 10:
        found.append(f'R123-6: the Kotlin test has {test.count("@Test")} cases; at least 10 are required')
    if '/r123/stat_test_corpus.tsv' not in test:
        found.append('R123-6: the Kotlin test does not read the R123 corpus resource')
    for literal in ('#NUM!', '#VALUE!', '#NAME?'):
        if literal not in test:
            found.append(f'R123-6: the Kotlin test never asserts {literal}')

    # R123-7 no regression in the kernels this round reuses.
    for needle in KEEP:
        if needle not in source:
            found.append(f'R123-7: the pre-existing kernel text changed or vanished: {needle[:48]}')

    summary = {
        'names': len(NAMES),
        'rows': len(corpus),
        'error_rows': sum(1 for row in corpus if row[2].startswith('#')),
        'tests': test.count('@Test'),
        'tolerance': float(tolerance.group(1)) if tolerance else None,
    }
    return found, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for rule, text in RULES.items():
            print(f'{rule}\t{text}')
        return 0
    found, summary = violations(args.root)
    if found:
        for item in found:
            print(item)
        return 1
    print(f"R123_STAT_OK names={summary['names']} rows={summary['rows']} error_rows={summary['error_rows']} "
          f"tests={summary['tests']} tolerance={summary['tolerance']:g}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
